import { test, expect } from '@playwright/test';
import { login, createSpace, api } from './helpers.mjs';
import { randomUUID } from 'node:crypto';

test('global landing, cross-space recent files and expanding list without empty preview', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', entry => { if (entry.type() === 'error') errors.push(entry.text()); });
  await login(page);
  const name = '概览-' + randomUUID().slice(0, 6);
  await createSpace(page, name);
  const firstSpace = await page.getByLabel('当前空间').inputValue();
  const title = name + '.txt';
  await page.getByLabel('选择上传文件').setInputFiles({ name: title, mimeType: 'text/plain', buffer: Buffer.from('真实的概览入口测试文档。') });
  await expect(page.getByLabel('上传队列').getByText('原件已保存', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: '收起上传队列' }).click();
  await createSpace(page, name + '-第二空间');
  await page.goto('/');
  const home = page.getByRole('region', { name: '系统概览', exact: true });
  await expect(home).toBeVisible();
  await expect(page.locator('.file-collection,.detail-shell')).toHaveCount(0);
  const summary = (await api(page, '/system/summary')).data;
  await expect(home.locator('.overview-metric').filter({ hasText: '全部档案' }).locator('strong')).toHaveText(String(summary.documents_total));
  await expect(home.locator('.overview-document').filter({ hasText: title })).toBeVisible();
  await page.screenshot({ path: '/tmp/juanzhan-home-desktop.png' });
  await home.locator('.overview-document').filter({ hasText: title }).click();
  await expect(page.getByLabel('当前空间')).toHaveValue(firstSpace);
  await expect(page.getByRole('region', { name: '档案详情', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '返回档案列表', exact: true }).click();
  await expect(page.locator('.detail-shell')).toHaveCount(0);
  const library = page.getByRole('region', { name: '档案列表', exact: true });
  const bounds = await library.boundingBox();
  expect(bounds.width).toBeGreaterThan(1100);
  await page.screenshot({ path: '/tmp/juanzhan-expanded-list-desktop.png' });
  await page.reload();
  await expect(library).toBeVisible();
  await expect(home).toHaveCount(0);
  await page.getByRole('navigation').getByRole('button', { name: '系统概览', exact: true }).click();
  await expect(home).toBeVisible();
  await page.goBack();
  await expect(library).toBeVisible();
  await page.goForward();
  await expect(home).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(home).toBeVisible();
  await expect(home.locator('.overview-metric').first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/juanzhan-home-mobile.png' });
  await home.getByRole('button', { name: '查看任务', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '任务中心', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await home.getByRole('button', { name: '进入档案列表', exact: true }).click();
  await expect(library).toBeVisible();
  await expect(page.locator('.detail-shell')).toHaveCount(0);
  expect(errors).toEqual([]);
});
