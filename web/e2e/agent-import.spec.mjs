import {test,expect} from '@playwright/test';
import {login,createSpace,api} from './helpers.mjs';
test('explicit import grant, file and template submission render cited Agent overview',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await login(page);await createSpace(page,'Agent模板验证');
 const space=await page.getByLabel('当前空间').inputValue();
 await page.getByRole('button',{name:'系统设置',exact:true}).click();
 await page.getByRole('button',{name:'Agent 接入',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Agent 接入',exact:true});
 const grant=dialog.getByLabel('允许导入原件及提交分析');await expect(grant).not.toBeChecked();await grant.check();
 await dialog.getByLabel('名称',{exact:true}).fill('浏览器外部Agent');
 await dialog.getByRole('checkbox',{name:'Agent模板验证',exact:true}).check();
 await dialog.getByRole('button',{name:'创建凭据',exact:true}).click();
 const token=await dialog.getByLabel('Agent Token',{exact:true}).inputValue();
 const h={Authorization:'Bearer '+token};
 await dialog.getByRole('button',{name:'关闭Agent 接入',exact:true}).click();
 const text='测试合同：甲方为示例公司，乙方为示例服务商。验收通过后支付1000元。';
 const response=await page.request.post(`/api/v1/agent/imports/ui-contract?space_id=${space}&filename=contract.txt`,{headers:{...h,'Content-Type':'application/octet-stream'},data:Buffer.from(text)});
 expect(response.status()).toBe(201);const saved=await response.json();
 const templates=await (await page.request.get('/api/v1/agent/analysis-templates',{headers:h})).json();
 const template=templates.templates.find(item=>item.id==='contract');
 const finding={text:'验收通过后支付1000元。',basis:'explicit',sources:[{start:0,end:text.length,quote:text}]};
 const body={submission_id:'first',revision_id:saved.revision_id,original_sha256:saved.original_sha256,template_id:'contract',template_version:1,agent_name:'浏览器外部Agent',markdown:text,summary:[{...finding,text:'这份采购合同明确双方合作关系，以验收作为付款前提。'},{...finding,text:'甲方为示例公司，乙方为示例服务商。'},finding],fields:{...template.fields,payment_terms:finding},additional_points:[]};
 const submitted=await page.request.post(`/api/v1/agent/imports/${saved.id}/analyses`,{headers:h,data:body});expect(submitted.status()).toBe(201);
 const localRequests=[];page.on('request',request=>{if(/\/documents\/[^/]+\/overview(?:\?|$)/.test(request.url()))localRequests.push(request.url());});
 await page.reload();await page.getByLabel('当前空间').selectOption(space);
 await page.getByRole('button',{name:'全部档案',exact:true}).click();
 await page.getByRole('region',{name:'档案列表',exact:true}).getByRole('button').filter({hasText:'contract.txt'}).click();
 const analysis=page.getByRole('region',{name:'Agent分析',exact:true});
 await expect(analysis.getByRole('heading',{name:'内容概览 · Agent 提取'})).toBeVisible();
 await expect(analysis).toContainText('验收通过后支付1000元');
 await analysis.getByText('原文依据',{exact:true}).first().click();
 await expect(analysis.getByText(text,{exact:false}).first()).toBeVisible();
 await page.screenshot({path:'/tmp/juanzhan-agent-import-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/juanzhan-agent-import-mobile.png'});
 const original=await page.request.get(`/api/v1/documents/${saved.document_id}/download`);expect((await original.body()).toString()).toBe(text);
 await expect(page.getByRole('region',{name:'文档概览',exact:true})).toHaveCount(0);
 expect(localRequests).toEqual([]);
 expect(errors).toEqual([]);
});
